export function frameBrandForPath(path: string) {
  const normalized = path.replace(/^\/+|\/+$/g, "");
  return FRAME_BRAND_LANDINGS.find((entry) => normalized === `opravy/${entry.slug}`);
}

export function frameBrandForName(brand: string) {
  return FRAME_BRAND_LANDINGS.find((entry) => entry.brand === brand);
}
