function hasCorrectivePower(values?: string[]) {
  return values?.some((value) => {
    const normalized = value.replace("−", "-").replace(",", ".").trim();
    const parsed = Number.parseFloat(normalized);
    return Number.isFinite(parsed) && parsed !== 0;
  }) ?? false;
}

